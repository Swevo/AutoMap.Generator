    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx =>
        {
            ctx.AddSource("AutoMapAttributes.g.cs", SourceText.From(AttributeSource, Encoding.UTF8));
            ctx.AddSource("AutoMapInterface.g.cs",  SourceText.From(InterfaceSource,  Encoding.UTF8));
        });

        // [Map] — attribute sits on the source type
        var mapPipeline = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "AutoMap.MapAttribute",
                predicate: static (n, _) => IsTypeSyntax(n),
                transform: static (ctx, ct) => TransformAttributes(ctx, ct, isMapFrom: false))
            .SelectMany(static (arr, _) => arr);

        // [MapFrom] — attribute sits on the destination type
        var mapFromPipeline = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "AutoMap.MapFromAttribute",
                predicate: static (n, _) => IsTypeSyntax(n),
                transform: static (ctx, ct) => TransformAttributes(ctx, ct, isMapFrom: true))
            .SelectMany(static (arr, _) => arr);

        // IMapFrom<T> — convention-based: class implements IMapFrom<TSource>
        var interfacePipeline = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (n, _) => n is TypeDeclarationSyntax { BaseList: { } },
                transform: static (ctx, ct) => TransformMapFromInterface(ctx, ct))
            .Where(static arr => !arr.IsEmpty)
            .SelectMany(static (arr, _) => arr);

        // [MapExternal] — both source and destination types are given explicitly, so it can be placed
        // on any accessible placeholder type to register a mapping between two types you don't own.
        var mapExternalPipeline = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "AutoMap.MapExternalAttribute",
                predicate: static (n, _) => IsTypeSyntax(n),
                transform: static (ctx, ct) => TransformExternalAttributes(ctx, ct))
            .SelectMany(static (arr, _) => arr);

        var allMappings = mapPipeline.Collect()
            .Combine(mapFromPipeline.Collect())
            .Combine(interfacePipeline.Collect())
            .Combine(mapExternalPipeline.Collect());

        context.RegisterSourceOutput(allMappings, static (spc, pair) =>
            GenerateSource(spc, pair.Left.Left.Left.AddRange(pair.Left.Left.Right)
                .AddRange(pair.Left.Right).AddRange(pair.Right)));
    }

    private static bool IsTypeSyntax(SyntaxNode n) =>
        n is ClassDeclarationSyntax or RecordDeclarationSyntax or StructDeclarationSyntax;

    // ── Transform: one call per decorated type, returns one MappingInfo per attribute ─

    private static ImmutableArray<MappingInfo> TransformAttributes(
        GeneratorAttributeSyntaxContext ctx,
        System.Threading.CancellationToken ct,
        bool isMapFrom)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol decoratedSymbol)
            return ImmutableArray<MappingInfo>.Empty;

        var builder = ImmutableArray.CreateBuilder<MappingInfo>(ctx.Attributes.Length);

        foreach (var attr in ctx.Attributes)
        {
            ct.ThrowIfCancellationRequested();

            if (attr.ConstructorArguments.Length == 0) continue;
            if (attr.ConstructorArguments[0].Value is not INamedTypeSymbol otherSymbol)
            {
                // AM003 — type could not be resolved
                builder.Add(new MappingInfo(
                    string.Empty, string.Empty, string.Empty,
                    ImmutableArray<PropertyMapping>.Empty,
                    ImmutableArray<UnresolvedProperty>.Empty,
                    ImmutableArray.Create(new DiagnosticInfo("AM003",
                        ImmutableArray.Create(isMapFrom ? "MapFromAttribute" : "MapAttribute", decoratedSymbol.Name))),
                    false));
                continue;
            }

            var sourceSymbol = isMapFrom ? otherSymbol : decoratedSymbol;
            var destSymbol   = isMapFrom ? decoratedSymbol : otherSymbol;

            string? methodName = null;
            bool reverse = false;
            bool strict = false;
            bool generateProjection = false;
            bool generateUpdate = false;
            foreach (var na in attr.NamedArguments)
            {
                if (na.Key == "MethodName") methodName = na.Value.Value as string;
                if (na.Key == "Reverse"   ) reverse    = na.Value.Value is true;
                if (na.Key == "Strict"    ) strict     = na.Value.Value is true;
                if (na.Key == "GenerateProjection") generateProjection = na.Value.Value is true;
                if (na.Key == "GenerateUpdate") generateUpdate = na.Value.Value is true;
            }

            builder.Add(BuildMappingInfo(sourceSymbol, destSymbol, methodName, ctx.SemanticModel.Compilation, strict,
                generateProjection: generateProjection, generateUpdate: generateUpdate));

            // When Reverse = true, also generate the opposite direction
            if (reverse)
                builder.Add(BuildReverseMappingInfo(sourceSymbol, destSymbol, ctx.SemanticModel.Compilation, strict));
        }

        return builder.ToImmutable();
    }

    // ── IMapFrom<T> convention pipeline ──────────────────────────────────────

    // ── [MapExternal] pipeline — both types given explicitly via constructor args ─────

    private static ImmutableArray<MappingInfo> TransformExternalAttributes(
        GeneratorAttributeSyntaxContext ctx,
        System.Threading.CancellationToken ct)
    {
        var builder = ImmutableArray.CreateBuilder<MappingInfo>(ctx.Attributes.Length);

        foreach (var attr in ctx.Attributes)
        {
            ct.ThrowIfCancellationRequested();

            if (attr.ConstructorArguments.Length < 2) continue;

            if (attr.ConstructorArguments[0].Value is not INamedTypeSymbol sourceSymbol
                || attr.ConstructorArguments[1].Value is not INamedTypeSymbol destSymbol)
            {
                // AM003 — one or both types could not be resolved
                builder.Add(new MappingInfo(
                    string.Empty, string.Empty, string.Empty,
                    ImmutableArray<PropertyMapping>.Empty,
                    ImmutableArray<UnresolvedProperty>.Empty,
                    ImmutableArray.Create(new DiagnosticInfo("AM003",
                        ImmutableArray.Create("MapExternalAttribute", ctx.TargetSymbol.Name))),
                    false));
                continue;
            }

            string? methodName = null;
            bool reverse = false;
            bool strict = false;
            bool generateUpdate = false;
            foreach (var na in attr.NamedArguments)
            {
                if (na.Key == "MethodName") methodName = na.Value.Value as string;
                if (na.Key == "Reverse"   ) reverse    = na.Value.Value is true;
                if (na.Key == "Strict"    ) strict     = na.Value.Value is true;
                if (na.Key == "GenerateUpdate") generateUpdate = na.Value.Value is true;
            }

            builder.Add(BuildMappingInfo(sourceSymbol, destSymbol, methodName, ctx.SemanticModel.Compilation, strict,
                generateUpdate: generateUpdate));

            if (reverse)
                builder.Add(BuildReverseMappingInfo(sourceSymbol, destSymbol, ctx.SemanticModel.Compilation, strict));
        }

        return builder.ToImmutable();
    }

    private static ImmutableArray<MappingInfo> TransformMapFromInterface(
        GeneratorSyntaxContext ctx,
        System.Threading.CancellationToken ct)
    {
        if (ctx.Node is not TypeDeclarationSyntax typeDecl) return ImmutableArray<MappingInfo>.Empty;
        if (ctx.SemanticModel.GetDeclaredSymbol(typeDecl, ct) is not INamedTypeSymbol destSymbol)
            return ImmutableArray<MappingInfo>.Empty;

        var builder = ImmutableArray.CreateBuilder<MappingInfo>();

        foreach (var iface in destSymbol.AllInterfaces)
        {
            ct.ThrowIfCancellationRequested();
            if (iface.OriginalDefinition.ToDisplayString() != "AutoMap.IMapFrom<TSource>") continue;
            if (iface.TypeArguments.Length != 1) continue;
            if (iface.TypeArguments[0] is not INamedTypeSymbol sourceSymbol) continue;

            builder.Add(BuildMappingInfo(sourceSymbol, destSymbol, null, ctx.SemanticModel.Compilation));
        }

        return builder.ToImmutable();
    }

    // ── Build one MappingInfo from resolved symbols ───────────────────────────

    internal static MappingInfo BuildMappingInfo(
        INamedTypeSymbol sourceSymbol,
        INamedTypeSymbol destSymbol,
        string? methodName,
        Compilation compilation,
        bool isStrict = false,
        bool reverse = false,
        bool generateProjection = false,
        bool generateUpdate = false)
    {
        var sourceFqn = sourceSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var destFqn   = destSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var effectiveMethod = methodName ?? "To" + destSymbol.Name;

        // [TrimStrings] — check on both the source and dest type (either placement works)
        bool trimStrings = HasAttribute(sourceSymbol, "AutoMap.TrimStringsAttribute")
                        || HasAttribute(destSymbol,   "AutoMap.TrimStringsAttribute");

        // [MapNamingConvention] — check on both the source and dest type (either placement works)
        bool namingConvention = HasAttribute(sourceSymbol, "AutoMap.MapNamingConventionAttribute")
                              || HasAttribute(destSymbol,   "AutoMap.MapNamingConventionAttribute");

        // Build a lookup of all readable source properties (name → symbol)
        var sourceProps = new Dictionary<string, IPropertySymbol>(StringComparer.OrdinalIgnoreCase);
        // Normalized (separator/case-insensitive) lookup, only populated when [MapNamingConvention] is present.
        var normalizedSourceProps = namingConvention
            ? new Dictionary<string, IPropertySymbol>(StringComparer.Ordinal)
            : null;
        foreach (var p in GetAllProperties(sourceSymbol))
        {
            if (p.IsStatic || p.IsIndexer) continue;
            if (p.GetMethod == null || p.GetMethod.DeclaredAccessibility != Accessibility.Public) continue;
            if (!sourceProps.ContainsKey(p.Name))
                sourceProps[p.Name] = p;
            if (normalizedSourceProps != null && !normalizedSourceProps.ContainsKey(NormalizeName(p.Name)))
                normalizedSourceProps[NormalizeName(p.Name)] = p;
        }

        var mappings             = ImmutableArray.CreateBuilder<PropertyMapping>();
        var unresolvedProperties = ImmutableArray.CreateBuilder<UnresolvedProperty>();
        var diagnostics          = ImmutableArray.CreateBuilder<DiagnosticInfo>();

        // ── XML doc bookkeeping ──────────────────────────────────────────────
        // Human-readable notes describing what happened to each property, surfaced later
        // as an XML doc comment on the generated method (see BuildDocComment).
        var docFlattened = ImmutableArray.CreateBuilder<string>();
        var docDefaulted = ImmutableArray.CreateBuilder<string>();
        var docIgnored   = ImmutableArray.CreateBuilder<string>();
        var docCustom    = ImmutableArray.CreateBuilder<string>();

        foreach (var destProp in GetAllProperties(destSymbol))
        {
            if (destProp.IsStatic || destProp.IsIndexer) continue;

            // Must have a publicly accessible setter (regular or init)
            var setter = destProp.SetMethod;
            if (setter == null || setter.DeclaredAccessibility != Accessibility.Public) continue;

            // [MapIgnore]
            if (HasAttribute(destProp, "AutoMap.MapIgnoreAttribute")) { docIgnored.Add(destProp.Name); continue; }

            // Collect all per-property control attributes in one pass
            string? mapWithExpr    = null;
            string? mapDefaultExpr = null;
            string? mapWhenCond    = null;
            string? mapWhenFallback = null;
            string? srcOverrideName = null;
            string? mapFormatStr   = null;
            INamedTypeSymbol? mapConverterType = null;
            string? mapConverterMethod = null;

            foreach (var a in destProp.GetAttributes())
            {
                var fqn = a.AttributeClass?.ToDisplayString();
                if (fqn == "AutoMap.MapWithAttribute" && a.ConstructorArguments.Length > 0)
                    mapWithExpr = a.ConstructorArguments[0].Value as string;
                else if (fqn == "AutoMap.MapDefaultAttribute" && a.ConstructorArguments.Length > 0)
                    mapDefaultExpr = a.ConstructorArguments[0].Value as string;
                else if (fqn == "AutoMap.MapPropertyAttribute" && a.ConstructorArguments.Length > 0)
                    srcOverrideName = a.ConstructorArguments[0].Value as string;
                else if (fqn == "AutoMap.MapWhenAttribute" && a.ConstructorArguments.Length > 0)
                {
                    mapWhenCond = a.ConstructorArguments[0].Value as string;
                    foreach (var na in a.NamedArguments)
                        if (na.Key == "Fallback") mapWhenFallback = na.Value.Value as string;
                }
                else if (fqn == "AutoMap.MapFormatAttribute" && a.ConstructorArguments.Length > 0)
                    mapFormatStr = a.ConstructorArguments[0].Value as string;
                else if (fqn == "AutoMap.MapConverterAttribute" && a.ConstructorArguments.Length > 1)
                {
                    mapConverterType = a.ConstructorArguments[0].Value as INamedTypeSymbol;
                    mapConverterMethod = a.ConstructorArguments[1].Value as string;
                }
            }

            if (mapWithExpr != null)
            {
                // [MapWith] — custom expression, optionally wrapped by [MapWhen]
                var expr = mapWhenCond != null
                    ? $"{mapWhenCond} ? {mapWithExpr} : {mapWhenFallback ?? "default"}"
                    : mapWithExpr;
                mappings.Add(new PropertyMapping(destProp.Name, destProp.Name, expr));
                docCustom.Add($"{destProp.Name} ([MapWith])");
                continue;
            }

            string lookupName = srcOverrideName ?? destProp.Name;

            // [MapNamingConvention] — try a separator/case-insensitive match before falling back
            // to flattening, e.g. a "customer_name" source property matching "CustomerName" dest property.
            if (srcOverrideName == null && normalizedSourceProps != null && !sourceProps.ContainsKey(lookupName)
                && normalizedSourceProps.TryGetValue(NormalizeName(lookupName), out var normalizedMatch))
            {
                lookupName = normalizedMatch.Name;
            }

            if (!sourceProps.TryGetValue(lookupName, out var srcProp))
            {
                if (srcOverrideName != null)
                {
                    // AM002 — explicit source name missing
                    diagnostics.Add(new DiagnosticInfo("AM002",
                        ImmutableArray.Create(srcOverrideName, destSymbol.Name, destProp.Name, sourceSymbol.Name)));
                }
                else
                {
                    // Try flattening: CustomerName → src.Customer?.Name
                    var flatPath = TryFlattenPath(destProp.Name, sourceProps, "src", false, 0);
                    if (flatPath != null)
                    {
                        var expr = mapDefaultExpr != null ? $"{flatPath} ?? {mapDefaultExpr}" : flatPath;
                        mappings.Add(new PropertyMapping(destProp.Name, destProp.Name,
                            WrapWhen(expr, mapWhenCond, mapWhenFallback)));
                        docFlattened.Add($"{destProp.Name} ({flatPath})");
                        if (mapDefaultExpr != null) docDefaulted.Add($"{destProp.Name} (?? {mapDefaultExpr})");
                        if (mapWhenCond != null) docCustom.Add($"{destProp.Name} ([MapWhen])");
                    }
                }
                continue;
            }

            // Check type compatibility
            var csharp = compilation as Microsoft.CodeAnalysis.CSharp.CSharpCompilation;
            bool typeCompatible;
            if (csharp != null)
            {
                var conv = csharp.ClassifyConversion(srcProp.Type, destProp.Type);
                typeCompatible = conv.IsIdentity || conv.IsImplicit;
            }
            else
            {
                var srcTypeFqn  = srcProp.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).TrimEnd('?');
                var destTypeFqn = destProp.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).TrimEnd('?');
                typeCompatible = srcTypeFqn == destTypeFqn;
            }

            if (mapFormatStr != null)
            {
                // [MapFormat] — bypasses type compatibility; emits .ToString("format")
                // Use ?. when source is a reference type or a nullable value type (Nullable<T>)
                bool isNullableStruct = srcProp.Type is INamedTypeSymbol ntf &&
                    ntf.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;
                var accessOp = (!srcProp.Type.IsValueType || isNullableStruct) ? "?." : ".";
                var formatted = $"src.{lookupName}{accessOp}ToString(\"{mapFormatStr}\")";
                mappings.Add(new PropertyMapping(destProp.Name, lookupName,
                    WrapWhen(formatted, mapWhenCond, mapWhenFallback)));
                docCustom.Add($"{destProp.Name} ([MapFormat])");
                if (mapWhenCond != null) docCustom.Add($"{destProp.Name} ([MapWhen])");
            }
            else if (mapConverterType != null && mapConverterMethod != null)
            {
                // [MapConverter] — bypasses type compatibility; calls a user-supplied static conversion method
                var converterFqn = mapConverterType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var converted = $"{converterFqn}.{mapConverterMethod}(src.{lookupName})";
                mappings.Add(new PropertyMapping(destProp.Name, lookupName,
                    WrapWhen(converted, mapWhenCond, mapWhenFallback)));
                docCustom.Add($"{destProp.Name} ([MapConverter])");
                if (mapWhenCond != null) docCustom.Add($"{destProp.Name} ([MapWhen])");
            }
            else if (typeCompatible)
            {
                string? finalExpr = null;

                if (mapDefaultExpr != null || mapWhenCond != null)
                {
                    var baseExpr = mapDefaultExpr != null
                        ? $"src.{lookupName} ?? {mapDefaultExpr}"
                        : $"src.{lookupName}";
                    finalExpr = WrapWhen(baseExpr, mapWhenCond, mapWhenFallback);
                    if (mapDefaultExpr != null) docDefaulted.Add($"{destProp.Name} (?? {mapDefaultExpr})");
                    if (mapWhenCond != null) docCustom.Add($"{destProp.Name} ([MapWhen])");
                }
                else if (trimStrings && IsStringType(destProp.Type))
                {
                    // [TrimStrings] — wrap string property with ?.Trim()
                    finalExpr = $"src.{lookupName}?.Trim()";
                }

                mappings.Add(new PropertyMapping(destProp.Name, lookupName, finalExpr));
            }
            else if (srcProp.Type.TypeKind == TypeKind.Enum
                  && destProp.Type.TypeKind == TypeKind.Enum
                  && srcProp.Type is INamedTypeSymbol srcEnum
                  && destProp.Type is INamedTypeSymbol destEnum)
            {
                var switchExpr = BuildEnumSwitchExpression(
                    $"src.{lookupName}", srcEnum, destEnum,
                    destEnum.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    diagnostics);
                mappings.Add(new PropertyMapping(destProp.Name, lookupName,
                    WrapWhen(switchExpr, mapWhenCond, mapWhenFallback)));
            }
            else
            {
                // May be resolvable as nested or collection mapping — defer to GenerateSource
                var unresolved = BuildUnresolvedProperty(destProp.Name, lookupName, srcProp.Type, destProp.Type);
                if (unresolved != null)
                    unresolvedProperties.Add(unresolved);
                // else: truly incompatible (e.g. different primitive types) — silently skip
            }
        }

        // ── Constructor mapping detection ──────────────────────────────────────
        // Use constructor mapping when:
        //   a) dest has [MapConstructor] attribute, OR
        //   b) dest has no public parameterless constructor
        bool hasParamlessCtor = false;
        foreach (var ctor in destSymbol.Constructors)
        {
            if (!ctor.IsStatic && ctor.DeclaredAccessibility == Accessibility.Public
                && ctor.Parameters.Length == 0)
            { hasParamlessCtor = true; break; }
        }

        bool hasMapConstructorAttr = HasAttribute(destSymbol, "AutoMap.MapConstructorAttribute");
        var ctorParams = ImmutableArray<CtorParamMapping>.Empty;

        if (!hasParamlessCtor || hasMapConstructorAttr)
        {
            // Pick the best (longest) public constructor
            IMethodSymbol? bestCtor = null;
            foreach (var ctor in destSymbol.Constructors)
            {
                if (ctor.IsStatic || ctor.DeclaredAccessibility != Accessibility.Public) continue;
                if (bestCtor == null || ctor.Parameters.Length > bestCtor.Parameters.Length)
                    bestCtor = ctor;
            }

            if (bestCtor != null)
            {
                var ctorBuilder = ImmutableArray.CreateBuilder<CtorParamMapping>(bestCtor.Parameters.Length);
                var ctorParamNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

                foreach (var param in bestCtor.Parameters)
                {
                    sourceProps.TryGetValue(param.Name, out var matchedProp);

                    if (matchedProp == null)
                    {
                        // AM005 — no matching source property for ctor param
                        diagnostics.Add(new DiagnosticInfo("AM005",
                            ImmutableArray.Create(param.Name, destSymbol.Name, sourceSymbol.Name)));
                        ctorBuilder.Add(new CtorParamMapping(param.Name, null));
                    }
                    else
                    {
                        ctorBuilder.Add(new CtorParamMapping(param.Name, matchedProp.Name));
                        ctorParamNames.Add(matchedProp.Name);
                    }
                }

                ctorParams = ctorBuilder.ToImmutable();

                // Remove ctor-covered properties from object-initializer mappings to avoid duplication
                var filtered = ImmutableArray.CreateBuilder<PropertyMapping>();
                foreach (var pm in mappings)
                    if (!ctorParamNames.Contains(pm.SourcePropertyName))
                        filtered.Add(pm);
                mappings = filtered;
            }
        }

        // AM001 moved to GenerateSource (needs all mappings to know if deferred props resolve)
        var matchedMembers = mappings.Count + ctorParams.Count(p => p.SourcePropertyName != null);

        return new MappingInfo(
            sourceFqn, destFqn, effectiveMethod,
            mappings.ToImmutable(),
            unresolvedProperties.ToImmutable(),
            diagnostics.ToImmutable(),
            sourceSymbol.IsValueType,
            ctorParams,
            trimStrings,
            isStrict,
            reverse,
            matchedMembers,
            generateProjection,
            docFlattened.ToImmutable(),
            docDefaulted.ToImmutable(),
            docIgnored.ToImmutable(),
            docCustom.ToImmutable(),
            generateUpdate);
    }

    private static MappingInfo BuildReverseMappingInfo(
        INamedTypeSymbol originalSourceSymbol,
        INamedTypeSymbol originalDestSymbol,
        Compilation compilation,
        bool isStrict = false)
    {
        var reverseSourceSymbol = originalDestSymbol;
        var reverseDestSymbol = originalSourceSymbol;

        var sourceFqn = reverseSourceSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var destFqn = reverseDestSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var methodName = "To" + originalSourceSymbol.Name;

        bool trimStrings = HasAttribute(reverseSourceSymbol, "AutoMap.TrimStringsAttribute")
                        || HasAttribute(reverseDestSymbol, "AutoMap.TrimStringsAttribute");

        var sourceProps = BuildReadablePropLookup(reverseSourceSymbol);
        var reverseLookup = new Dictionary<string, (string SourcePropertyName, bool SkipReverse)>(StringComparer.OrdinalIgnoreCase);

        foreach (var forwardDestProp in GetAllProperties(originalDestSymbol))
        {
            if (forwardDestProp.IsStatic || forwardDestProp.IsIndexer) continue;
            if (forwardDestProp.GetMethod?.DeclaredAccessibility != Accessibility.Public) continue;

            string lookupName = forwardDestProp.Name;
            bool skipReverse = false;

            foreach (var a in forwardDestProp.GetAttributes())
            {
                var fqn = a.AttributeClass?.ToDisplayString();
                if (fqn == "AutoMap.MapIgnoreAttribute" || fqn == "AutoMap.MapWithAttribute")
                    skipReverse = true;
                else if (fqn == "AutoMap.MapPropertyAttribute" && a.ConstructorArguments.Length > 0)
                    lookupName = a.ConstructorArguments[0].Value as string ?? lookupName;
            }

            if (!reverseLookup.ContainsKey(lookupName))
                reverseLookup[lookupName] = (forwardDestProp.Name, skipReverse);
        }

        var mappings = ImmutableArray.CreateBuilder<PropertyMapping>();
        var unresolvedProperties = ImmutableArray.CreateBuilder<UnresolvedProperty>();
        var diagnostics = ImmutableArray.CreateBuilder<DiagnosticInfo>();

        foreach (var destProp in GetAllProperties(reverseDestSymbol))
        {
            if (destProp.IsStatic || destProp.IsIndexer) continue;

            var setter = destProp.SetMethod;
            if (setter == null || setter.DeclaredAccessibility != Accessibility.Public) continue;

            if (!reverseLookup.TryGetValue(destProp.Name, out var reverseInfo) || reverseInfo.SkipReverse) continue;
            if (!sourceProps.TryGetValue(reverseInfo.SourcePropertyName, out var srcProp)) continue;

            var csharp = compilation as Microsoft.CodeAnalysis.CSharp.CSharpCompilation;
            bool typeCompatible;
            if (csharp != null)
            {
                var conv = csharp.ClassifyConversion(srcProp.Type, destProp.Type);
                typeCompatible = conv.IsIdentity || conv.IsImplicit;
            }
            else
            {
                var srcTypeFqn = srcProp.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).TrimEnd('?');
                var destTypeFqn = destProp.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).TrimEnd('?');
                typeCompatible = srcTypeFqn == destTypeFqn;
            }

            if (typeCompatible)
            {
                var finalExpr = trimStrings && IsStringType(destProp.Type)
                    ? $"src.{srcProp.Name}?.Trim()"
                    : null;
                mappings.Add(new PropertyMapping(destProp.Name, srcProp.Name, finalExpr));
            }
            else if (srcProp.Type.TypeKind == TypeKind.Enum
                  && destProp.Type.TypeKind == TypeKind.Enum
                  && srcProp.Type is INamedTypeSymbol srcEnum
                  && destProp.Type is INamedTypeSymbol destEnum)
            {
                var switchExpr = BuildEnumSwitchExpression(
                    $"src.{srcProp.Name}", srcEnum, destEnum,
                    destEnum.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    diagnostics);
                mappings.Add(new PropertyMapping(destProp.Name, srcProp.Name, switchExpr));
            }
            else
            {
                var unresolved = BuildUnresolvedProperty(destProp.Name, srcProp.Name, srcProp.Type, destProp.Type);
                if (unresolved != null)
                    unresolvedProperties.Add(unresolved);
            }
        }

        bool hasParamlessCtor = false;
        foreach (var ctor in reverseDestSymbol.Constructors)
        {
            if (!ctor.IsStatic && ctor.DeclaredAccessibility == Accessibility.Public
                && ctor.Parameters.Length == 0)
            { hasParamlessCtor = true; break; }
        }

        bool hasMapConstructorAttr = HasAttribute(reverseDestSymbol, "AutoMap.MapConstructorAttribute");
        var ctorParams = ImmutableArray<CtorParamMapping>.Empty;

        if (!hasParamlessCtor || hasMapConstructorAttr)
        {
            IMethodSymbol? bestCtor = null;
            foreach (var ctor in reverseDestSymbol.Constructors)
            {
                if (ctor.IsStatic || ctor.DeclaredAccessibility != Accessibility.Public) continue;
                if (bestCtor == null || ctor.Parameters.Length > bestCtor.Parameters.Length)
                    bestCtor = ctor;
            }

            if (bestCtor != null)
            {
                var ctorBuilder = ImmutableArray.CreateBuilder<CtorParamMapping>(bestCtor.Parameters.Length);
                var ctorParamNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

                foreach (var param in bestCtor.Parameters)
                {
                    IPropertySymbol? matchedProp = null;
                    if (reverseLookup.TryGetValue(param.Name, out var reverseInfo)
                        && !reverseInfo.SkipReverse)
                    {
                        sourceProps.TryGetValue(reverseInfo.SourcePropertyName, out matchedProp);
                    }

                    if (matchedProp == null)
                    {
                        diagnostics.Add(new DiagnosticInfo("AM005",
                            ImmutableArray.Create(param.Name, reverseDestSymbol.Name, reverseSourceSymbol.Name)));
                        ctorBuilder.Add(new CtorParamMapping(param.Name, null));
                    }
                    else
                    {
                        ctorBuilder.Add(new CtorParamMapping(param.Name, matchedProp.Name));
                        ctorParamNames.Add(matchedProp.Name);
                    }
                }

                ctorParams = ctorBuilder.ToImmutable();

                var filtered = ImmutableArray.CreateBuilder<PropertyMapping>();
                foreach (var pm in mappings)
                    if (!ctorParamNames.Contains(pm.SourcePropertyName))
                        filtered.Add(pm);
                mappings = filtered;
            }
        }

        var matchedMembers = mappings.Count + ctorParams.Count(p => p.SourcePropertyName != null);

        return new MappingInfo(
            sourceFqn, destFqn, methodName,
            mappings.ToImmutable(),
            unresolvedProperties.ToImmutable(),
            diagnostics.ToImmutable(),
            reverseSourceSymbol.IsValueType,
            ctorParams,
            trimStrings,
            isStrict,
            reverse: true,
            matchedMembers: matchedMembers);
    }

    // ── Helpers ───────────────────────────────────────────────────────────────

    internal static IEnumerable<IPropertySymbol> GetAllProperties(INamedTypeSymbol type)
    {
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var current = (INamedTypeSymbol?)type;
        while (current != null && current.SpecialType != SpecialType.System_Object)
        {
            foreach (var member in current.GetMembers())
            {
                if (member is IPropertySymbol prop && seen.Add(prop.Name))
                    yield return prop;
            }
            current = current.BaseType;
        }
    }

    internal static bool HasAttribute(ISymbol symbol, string fullyQualifiedName)
    {
        foreach (var attr in symbol.GetAttributes())
            if (attr.AttributeClass?.ToDisplayString() == fullyQualifiedName)
                return true;
        return false;
    }

    private static bool IsStringType(ITypeSymbol type)
    {
        var fqn = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        return fqn == "string" || fqn == "string?" || type.SpecialType == SpecialType.System_String;
    }

    private static UnresolvedProperty? BuildUnresolvedProperty(
        string destPropName, string srcPropName, ITypeSymbol srcType, ITypeSymbol destType)
    {
        var srcFqn  = srcType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var destFqn = destType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        // Dictionary<TKey, TValue> mapping — checked before the single-type-arg collection check,
        // since Dictionary<,> also implements IEnumerable<KeyValuePair<,>>.
        var srcDict  = GetDictionaryTypeArgs(srcType);
        var destDict = GetDictionaryTypeArgs(destType);
        if (srcDict != null && destDict != null && srcDict.Value.KeyFqn == destDict.Value.KeyFqn)
        {
            return new UnresolvedProperty(destPropName, srcPropName, srcFqn, destFqn,
                isCollection: true, srcDict.Value.ValueFqn, destDict.Value.ValueFqn, "Dictionary",
                isDictionary: true, keyFqn: srcDict.Value.KeyFqn);
        }
        if (srcDict != null || destDict != null)
            return null; // mixed dictionary/non-dictionary — incompatible

        var srcElemFqn  = GetCollectionElementFqn(srcType);
        var destElemFqn = GetCollectionElementFqn(destType);

        if (srcElemFqn != null && destElemFqn != null)
        {
            // Both are collection types
            string kind = destType is IArrayTypeSymbol ? "Array" : "List";
            return new UnresolvedProperty(destPropName, srcPropName, srcFqn, destFqn,
                isCollection: true, srcElemFqn, destElemFqn, kind);
        }

        if (srcElemFqn == null && destElemFqn == null)
        {
            // Both non-collection — potential nested object mapping
            return new UnresolvedProperty(destPropName, srcPropName, srcFqn, destFqn,
                isCollection: false, null, null, null);
        }

        return null; // mixed collection/non-collection — incompatible
    }

    private static string? GetCollectionElementFqn(ITypeSymbol type)
    {
        if (type is IArrayTypeSymbol arr)
            return arr.ElementType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        if (type is INamedTypeSymbol named && named.IsGenericType && named.TypeArguments.Length == 1)
        {
            var def = named.OriginalDefinition.ToDisplayString();
            if (def is "System.Collections.Generic.List<T>"
                    or "System.Collections.Generic.IEnumerable<T>"
                    or "System.Collections.Generic.ICollection<T>"
                    or "System.Collections.Generic.IList<T>"
                    or "System.Collections.Generic.IReadOnlyList<T>"
                    or "System.Collections.Generic.IReadOnlyCollection<T>")
                return named.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        }

        return null;
    }

    private static (string KeyFqn, string ValueFqn)? GetDictionaryTypeArgs(ITypeSymbol type)
    {
        if (type is INamedTypeSymbol named && named.IsGenericType && named.TypeArguments.Length == 2)
        {
            var def = named.OriginalDefinition.ToDisplayString();
            if (def is "System.Collections.Generic.Dictionary<TKey, TValue>"
                    or "System.Collections.Generic.IDictionary<TKey, TValue>"
                    or "System.Collections.Generic.IReadOnlyDictionary<TKey, TValue>")
            {
                return (named.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                        named.TypeArguments[1].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
            }
        }

        return null;
    }

    // ── Code generation ───────────────────────────────────────────────────────

    private static void GenerateSource(
        SourceProductionContext spc,
        ImmutableArray<MappingInfo> mappings)
    {
        // Deduplicate — same source+dest+method (IMapFrom<T> and [MapFrom] may both register)
        var seen = new HashSet<(string, string, string)>();
        var deduped = ImmutableArray.CreateBuilder<MappingInfo>(mappings.Length);
        foreach (var m in mappings)
        {
            if (!string.IsNullOrEmpty(m.SourceFqn) && !seen.Add((m.SourceFqn, m.DestFqn, m.MethodName)))
                continue;
            deduped.Add(m);
        }
        mappings = deduped.ToImmutable();

        // Build sourceFqn → (destFqn → methodName) lookup for resolving nested/collection
        var knownMappings = new Dictionary<string, Dictionary<string, string>>(StringComparer.Ordinal);
        foreach (var m in mappings)
        {
            if (string.IsNullOrEmpty(m.SourceFqn)) continue;
            if (m.Mappings.Length == 0 && m.CtorParams.Length == 0 && m.UnresolvedProperties.Length == 0) continue;
            if (!knownMappings.TryGetValue(m.SourceFqn, out var destMap))
                knownMappings[m.SourceFqn] = destMap = new Dictionary<string, string>(StringComparer.Ordinal);
            destMap[m.DestFqn] = m.MethodName;
        }

        // Resolve deferred (nested / collection) properties
        bool needsLinq = false;
        var resolvedExtras = new Dictionary<MappingInfo, List<(string DestProp, string Expr)>>();

        foreach (var m in mappings)
        {
            if (string.IsNullOrEmpty(m.SourceFqn)) continue;
            var extras = new List<(string, string)>();

            foreach (var up in m.UnresolvedProperties)
            {
                string? expr = null;

                if (up.IsDictionary && up.SourceElementFqn != null && up.DestElementFqn != null)
                {
                    needsLinq = true;
                    if (up.SourceElementFqn == up.DestElementFqn)
                    {
                        // Same value type — copy pairs into the destination dictionary shape
                        expr = $"src.{up.SourcePropertyName}?.ToDictionary(kv => kv.Key, kv => kv.Value)";
                    }
                    else if (knownMappings.TryGetValue(up.SourceElementFqn, out var vdm) &&
                             vdm.TryGetValue(up.DestElementFqn, out var vmethod))
                    {
                        expr = $"src.{up.SourcePropertyName}?.ToDictionary(kv => kv.Key, kv => kv.Value.{vmethod}())";
                    }
                }
                else if (up.IsCollection && up.SourceElementFqn != null && up.DestElementFqn != null)
                {
                    if (knownMappings.TryGetValue(up.SourceElementFqn, out var dm) &&
                        dm.TryGetValue(up.DestElementFqn, out var method))
                    {
                        needsLinq = true;
                        expr = up.DestCollectionKind == "Array"
                            ? $"src.{up.SourcePropertyName}?.Select(x => x.{method}()).ToArray()"
                            : $"src.{up.SourcePropertyName}?.Select(x => x.{method}()).ToList()";
                    }
                }
                else if (!up.IsCollection)
                {
                    if (knownMappings.TryGetValue(up.SourceTypeFqn, out var dm) &&
                        dm.TryGetValue(up.DestTypeFqn, out var method))
                    {
                        expr = $"src.{up.SourcePropertyName}?.{method}()";
                    }
                }

                if (expr != null)
                    extras.Add((up.DestPropertyName, expr));
                else
                {
                    var am004 = m.IsStrict ? AM004_Strict : AM004;
                    spc.ReportDiagnostic(Diagnostic.Create(am004, null,
                        up.DestPropertyName, SimpleName(m.DestFqn),
                        up.SourcePropertyName, SimpleName(m.SourceFqn)));
                }
            }

            resolvedExtras[m] = extras;
        }

        foreach (var m in mappings)
        {
            if (!m.Reverse || string.IsNullOrEmpty(m.SourceFqn)) continue;
            var extras = resolvedExtras.TryGetValue(m, out var ex) ? ex : null;
            if (m.MatchedMembers == 0 && (extras == null || extras.Count == 0))
                spc.ReportDiagnostic(Diagnostic.Create(AM007, null,
                    SimpleName(m.SourceFqn), SimpleName(m.DestFqn)));
        }

        // Report stored diagnostics (AM002, AM003, AM005)
        foreach (var m in mappings)
        {
            foreach (var d in m.Diagnostics)
            {
                var descriptor = d.Id switch { "AM002" => AM002, "AM003" => AM003, "AM005" => AM005, "AM006" => AM006, "AM007" => AM007, _ => AM001 };
                spc.ReportDiagnostic(Diagnostic.Create(descriptor, null, d.Args.ToArray<object>()));
            }
        }

        // AM001 — no properties at all (direct or resolved)
        foreach (var m in mappings)
        {
            if (m.Reverse || string.IsNullOrEmpty(m.SourceFqn) || m.Diagnostics.Length > 0) continue;
            var extras = resolvedExtras.TryGetValue(m, out var ex) ? ex : null;
            if (m.Mappings.Length == 0 && m.CtorParams.Length == 0 && (extras == null || extras.Count == 0))
            {
                var am001 = m.IsStrict ? AM001_Strict : AM001;
                spc.ReportDiagnostic(Diagnostic.Create(am001, null,
                    SimpleName(m.SourceFqn), SimpleName(m.DestFqn)));
            }
        }

        // Emit only mappings that have at least one property
        var valid = mappings
            .Where(m => !string.IsNullOrEmpty(m.SourceFqn))
            .Where(m => m.Mappings.Length > 0 || m.CtorParams.Length > 0 ||
                        (resolvedExtras.TryGetValue(m, out var ex) && ex.Count > 0))
            .ToList();

        if (valid.Count == 0) return;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated by AutoMap.Generator/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        // Collection helpers always need LINQ; per-property collection resolves may also need it
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Linq;");
        sb.AppendLine("using System.Linq.Expressions;");
        sb.AppendLine();
        sb.AppendLine("namespace AutoMap");
        sb.AppendLine("{");
        sb.AppendLine("    public static partial class AutoMapExtensions");
        sb.AppendLine("    {");

        foreach (var m in valid)
        {
            AppendMethodDocComment(sb, m);
            sb.AppendLine($"        public static {m.DestFqn} {m.MethodName}(this {m.SourceFqn} src)");
            sb.AppendLine("        {");
            if (!m.IsSourceValueType)
                sb.AppendLine("            if (src is null) throw new ArgumentNullException(nameof(src));");

            var extras = resolvedExtras.TryGetValue(m, out var ex) ? ex : null;
            bool hasInitProps = m.Mappings.Length > 0 || (extras != null && extras.Count > 0);

            if (m.UseConstructor)
            {
                // Emit: var result = new Dest(src.A, src.B, ...)
                var ctorArgs = string.Join(", ", m.CtorParams.Select(p =>
                    p.SourcePropertyName != null ? $"src.{p.SourcePropertyName}" : "default"));
                if (hasInitProps)
                {
                    sb.AppendLine($"            var result = new {m.DestFqn}({ctorArgs})");
                    sb.AppendLine("            {");
                    foreach (var p in m.Mappings)
                        sb.AppendLine($"                {p.DestPropertyName} = {p.CustomExpression ?? $"src.{p.SourcePropertyName}"},");
                    if (extras != null)
                        foreach (var (dp, expr) in extras)
                            sb.AppendLine($"                {dp} = {expr},");
                    sb.AppendLine("            };");
                }
                else
                {
                    sb.AppendLine($"            var result = new {m.DestFqn}({ctorArgs});");
                }
            }
            else
            {
                // Emit: var result = new Dest { A = src.A, ... }
                sb.AppendLine($"            var result = new {m.DestFqn}");
                sb.AppendLine("            {");
                foreach (var p in m.Mappings)
                    sb.AppendLine($"                {p.DestPropertyName} = {p.CustomExpression ?? $"src.{p.SourcePropertyName}"},");
                if (extras != null)
                    foreach (var (dp, expr) in extras)
                        sb.AppendLine($"                {dp} = {expr},");
                sb.AppendLine("            };");
            }

            sb.AppendLine($"            On{m.MethodName}(src, result);");
            sb.AppendLine("            return result;");
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        // UpdateFrom(TSource src) — patches an existing destination instance in place instead of
        // allocating a new one (equivalent to AutoMapper's Map(source, existingDestination)).
        // Only settable properties are patched; constructor-only properties are left untouched.
        foreach (var m in valid)
        {
            if (!m.GenerateUpdate) continue;

            var extras = resolvedExtras.TryGetValue(m, out var ex) ? ex : null;
            bool hasInitProps = m.Mappings.Length > 0 || (extras != null && extras.Count > 0);
            if (!hasInitProps) continue;

            sb.AppendLine($"        /// <summary>Patches <paramref name=\"dest\"/>'s settable properties from <paramref name=\"src\"/> in place, instead of allocating a new instance.</summary>");
            sb.AppendLine($"        public static {m.DestFqn} UpdateFrom(this {m.DestFqn} dest, {m.SourceFqn} src)");
            sb.AppendLine("        {");
            sb.AppendLine("            if (dest is null) throw new ArgumentNullException(nameof(dest));");
            if (!m.IsSourceValueType)
                sb.AppendLine("            if (src is null) throw new ArgumentNullException(nameof(src));");
            foreach (var p in m.Mappings)
                sb.AppendLine($"            dest.{p.DestPropertyName} = {p.CustomExpression ?? $"src.{p.SourcePropertyName}"};");
            if (extras != null)
                foreach (var (dp, expr) in extras)
                    sb.AppendLine($"            dest.{dp} = {expr};");
            sb.AppendLine("            return dest;");
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        // Collection mapping helpers — one per mapping (e.g. orders.ToOrderDtos())
        foreach (var m in valid)
        {
            var pluralMethod = m.MethodName + "s";
            sb.AppendLine($"        /// <summary>Maps each element in the sequence using <see cref=\"{m.MethodName}\"/>.</summary>");
            sb.AppendLine($"        public static IEnumerable<{m.DestFqn}> {pluralMethod}(");
            sb.AppendLine($"            this IEnumerable<{m.SourceFqn}> src)");
            sb.AppendLine($"            => src.Select(x => x.{m.MethodName}());");
            sb.AppendLine();
        }

        // Partial method hooks — one per mapping (user implements in their own partial class)
        foreach (var m in valid)
            sb.AppendLine($"        static partial void On{m.MethodName}({m.SourceFqn} src, {m.DestFqn} result);");

        sb.AppendLine();

        // IAutoMapper<TSource, TDest> implementations (static singleton per mapping)
        foreach (var m in valid)
        {
            var mapperName = $"{SimpleName(m.SourceFqn)}{m.MethodName}Mapper";
            sb.AppendLine($"        public sealed class {mapperName} : global::AutoMap.IAutoMapper<{m.SourceFqn}, {m.DestFqn}>");
            sb.AppendLine("        {");
            sb.AppendLine($"            public static readonly {mapperName} Instance = new {mapperName}();");
            sb.AppendLine($"            public {m.DestFqn} Map({m.SourceFqn} source) => source.{m.MethodName}();");
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        // Projection expressions — Expression<Func<TSource,TDest>> + IQueryable<TDest> helper,
        // so EF Core can translate the mapping to SQL (equivalent to AutoMapper's ProjectTo).
        foreach (var m in valid)
        {
            if (!m.GenerateProjection) continue;

            var extras = resolvedExtras.TryGetValue(m, out var ex) ? ex : null;
            var assignments = new List<(string DestProp, string Expr)>();
            foreach (var p in m.Mappings)
                assignments.Add((p.DestPropertyName, p.CustomExpression ?? $"src.{p.SourcePropertyName}"));
            if (extras != null)
                foreach (var (dp, expr) in extras)
                    assignments.Add((dp, expr));

            var ctorArgExprs = m.CtorParams.Select(p =>
                p.SourcePropertyName != null ? $"src.{p.SourcePropertyName}" : "default").ToList();

            // Expression<Func<,>> lambdas cannot contain the null-conditional operator (?.),
            // a switch expression, or a reference to another generated mapping method — reject those.
            string? incompatibleProp = null;
            foreach (var (destProp, expr) in assignments)
            {
                if (!IsExpressionTreeCompatible(expr)) { incompatibleProp = destProp; break; }
            }
            if (incompatibleProp == null)
                foreach (var arg in ctorArgExprs)
                    if (!IsExpressionTreeCompatible(arg)) { incompatibleProp = "(constructor argument)"; break; }

            if (incompatibleProp != null)
            {
                spc.ReportDiagnostic(Diagnostic.Create(AM008, null,
                    SimpleName(m.SourceFqn), SimpleName(m.DestFqn), incompatibleProp));
                continue;
            }

            sb.AppendLine($"        public static readonly Expression<Func<{m.SourceFqn}, {m.DestFqn}>> {m.MethodName}Expression = src =>");
            if (m.UseConstructor)
            {
                var ctorArgs = string.Join(", ", ctorArgExprs);
                if (assignments.Count > 0)
                {
                    sb.AppendLine($"            new {m.DestFqn}({ctorArgs})");
                    sb.AppendLine("            {");
                    foreach (var (destProp, expr) in assignments)
                        sb.AppendLine($"                {destProp} = {expr},");
                    sb.AppendLine("            };");
                }
                else
                {
                    sb.AppendLine($"            new {m.DestFqn}({ctorArgs});");
                }
            }
            else
            {
                sb.AppendLine($"            new {m.DestFqn}");
                sb.AppendLine("            {");
                foreach (var (destProp, expr) in assignments)
                    sb.AppendLine($"                {destProp} = {expr},");
                sb.AppendLine("            };");
            }
            sb.AppendLine();

            sb.AppendLine($"        /// <summary>Projects an <see cref=\"IQueryable{{T}}\"/> of <see cref=\"{SimpleName(m.SourceFqn)}\"/> directly to <see cref=\"{SimpleName(m.DestFqn)}\"/> using <see cref=\"{m.MethodName}Expression\"/>, so EF Core (or any IQueryable provider) can translate the projection into the underlying query.</summary>");
            sb.AppendLine($"        public static IQueryable<{m.DestFqn}> Project{m.MethodName}(this IQueryable<{m.SourceFqn}> source)");
            sb.AppendLine($"            => source.Select({m.MethodName}Expression);");
            sb.AppendLine();
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");

        spc.AddSource("AutoMapExtensions.g.cs",
            SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    /// <summary>
    /// Expression&lt;Func&lt;,&gt;&gt; lambdas cannot contain the null-conditional operator (?.) or a
    /// switch expression (C# compiler restriction: CS8072 / CS8829). Any generated snippet using either
    /// construct must be excluded from projection generation.
    /// </summary>
    internal static bool IsExpressionTreeCompatible(string expr) =>
        !expr.Contains("?.") && !expr.Contains(" switch") && !expr.Contains("switch\n") && !expr.Contains("switch{");

    /// <summary>
    /// Builds the ordered list of non-empty (Label, Value) doc/preview categories for a mapping —
    /// shared by <see cref="AppendMethodDocComment"/> (XML doc emission) and
    /// <see cref="AutoMapPreviewAnalyzer"/> (the AM011 one-line IDE preview), so both surfaces
    /// summarize the exact same information and can never drift out of sync.
    /// </summary>
    internal static List<(string Label, string Value)> GetDocCategories(MappingInfo m)
    {
        var categories = new List<(string Label, string Value)>();
        if (m.DocFlattened.Length > 0) categories.Add(("Flattened", string.Join(", ", m.DocFlattened)));
        if (m.DocDefaulted.Length > 0) categories.Add(("Defaulted", string.Join(", ", m.DocDefaulted)));
        if (m.DocIgnored.Length > 0) categories.Add(("Ignored", string.Join(", ", m.DocIgnored)));
        if (m.DocCustom.Length > 0) categories.Add(("Custom", string.Join(", ", m.DocCustom)));
        return categories;
    }

    /// <summary>
    /// Emits an XML doc comment above a generated mapping method summarizing which
    /// destination properties were flattened, defaulted, ignored, or custom-mapped.
    /// Only non-empty categories are included, so a simple 1:1 mapping gets a plain summary.
    /// </summary>
    private static void AppendMethodDocComment(StringBuilder sb, MappingInfo m)
    {
        sb.AppendLine($"        /// <summary>");
        sb.AppendLine($"        /// Maps <see cref=\"{SimpleName(m.SourceFqn)}\"/> to <see cref=\"{SimpleName(m.DestFqn)}\"/>.");
        foreach (var (label, value) in GetDocCategories(m))
            sb.AppendLine($"        /// {label}: {EscapeXmlDoc(value)}");
        sb.AppendLine($"        /// </summary>");
    }

    /// <summary>Escapes text embedded in a generated XML doc comment so arbitrary [MapDefault]/[MapWith] expressions can't break the comment.</summary>
    private static string EscapeXmlDoc(string text) =>
        text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");


    /// <summary>
    /// Normalizes a property name for [MapNamingConvention] matching by stripping separators
    /// (underscore, hyphen) and lowercasing, so "CustomerName", "customer_name", "customer-name"
    /// and "customerName" all collapse to the same key ("customername").
    /// </summary>
    internal static string NormalizeName(string name)
    {
        var sb = new StringBuilder(name.Length);
        foreach (var c in name)
        {
            if (c is '_' or '-') continue;
            sb.Append(char.ToLowerInvariant(c));
        }
        return sb.ToString();
    }

    internal static string SimpleName(string fqn)
    {
        // Strip global:: prefix — types in the global namespace use it but it is
        // not valid as part of a declared identifier.
        if (fqn.StartsWith("global::"))
            fqn = fqn.Substring("global::".Length);
        var last = fqn.LastIndexOf('.');
        return last >= 0 ? fqn.Substring(last + 1) : fqn;
    }

    private static string? WrapWhen(string expr, string? condition, string? fallback) =>
        condition != null ? $"{condition} ? {expr} : {fallback ?? "default"}" : expr;

    // ── Enum mapping helper ───────────────────────────────────────────────────

    private static string BuildEnumSwitchExpression(
        string srcAccessExpr,
        INamedTypeSymbol srcEnum,
        INamedTypeSymbol destEnum,
        string destEnumFqn,
        ImmutableArray<DiagnosticInfo>.Builder diagnostics)
    {
        var srcEnumFqn = srcEnum.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        // Build dest value lookup (name → canonical name)
        var destMembers = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var m in destEnum.GetMembers())
            if (m is IFieldSymbol f && f.HasConstantValue)
                destMembers[f.Name] = f.Name;

        var sb = new StringBuilder();
        sb.Append(srcAccessExpr);
        sb.Append(" switch { ");

        foreach (var m in srcEnum.GetMembers())
        {
            if (m is not IFieldSymbol f || !f.HasConstantValue) continue;

            // Check [MapEnum("DestValueName")] on this source member
            string? destValueName = null;
            foreach (var a in f.GetAttributes())
            {
                if (a.AttributeClass?.ToDisplayString() == "AutoMap.MapEnumAttribute"
                    && a.ConstructorArguments.Length > 0)
                { destValueName = a.ConstructorArguments[0].Value as string; break; }
            }

            // Fall back to name-match
            if (destValueName == null)
                destMembers.TryGetValue(f.Name, out destValueName);

            if (destValueName == null)
            {
                diagnostics.Add(new DiagnosticInfo("AM006",
                    ImmutableArray.Create(f.Name, srcEnum.Name, destEnum.Name)));
                continue; // unmatched — covered by _ => default
            }

            sb.Append($"{srcEnumFqn}.{f.Name} => {destEnumFqn}.{destValueName}, ");
        }

        sb.Append("_ => default }");
        return sb.ToString();
    }

    // ── Flattening helper ─────────────────────────────────────────────────────

    /// <summary>
    /// Attempts to flatten a dest property name into a dotted source access path.
    /// E.g. "CustomerName" → "src.Customer?.Name" when source has Customer.Name.
    /// Returns null when no path can be found.
    /// </summary>
    internal static string? TryFlattenPath(
        string name,
        Dictionary<string, IPropertySymbol> props,
        string currentExpr,
        bool accessViaNull,
        int depth)
    {
        if (depth >= 3) return null;

        for (int i = 1; i < name.Length; i++)
        {
            if (!char.IsUpper(name[i])) continue;

            var part = name.Substring(0, i);
            var rest = name.Substring(i);

            if (!props.TryGetValue(part, out var prop)) continue;
            if (prop.IsStatic || prop.IsIndexer) continue;
            if (prop.GetMethod?.DeclaredAccessibility != Accessibility.Public) continue;

            var accessOp = accessViaNull ? "?." : ".";
            var thisExpr = $"{currentExpr}{accessOp}{prop.Name}";

            if (prop.Type is not INamedTypeSymbol namedType) continue;

            var subProps = BuildReadablePropLookup(namedType);
            bool propIsRef = !prop.Type.IsValueType;

            if (subProps.TryGetValue(rest, out var subProp))
            {
                var op2 = propIsRef ? "?." : ".";
                return $"{thisExpr}{op2}{subProp.Name}";
            }

            var deeper = TryFlattenPath(rest, subProps, thisExpr, propIsRef, depth + 1);
            if (deeper != null) return deeper;
        }

        return null;
    }

    internal static Dictionary<string, IPropertySymbol> BuildReadablePropLookup(INamedTypeSymbol type)
    {
        var dict = new Dictionary<string, IPropertySymbol>(StringComparer.OrdinalIgnoreCase);
        foreach (var p in GetAllProperties(type))
        {
            if (p.IsStatic || p.IsIndexer) continue;
            if (p.GetMethod?.DeclaredAccessibility != Accessibility.Public) continue;
            if (!dict.ContainsKey(p.Name)) dict[p.Name] = p;
        }
        return dict;
    }
}

